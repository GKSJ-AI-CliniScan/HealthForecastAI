/**
 * A small caption under a score, band or recommendation list.
 *
 * opacity-75 (about 6:1 on both page and card backgrounds in light mode); a
 * lighter opacity-60 would sit right at the 4.5:1 WCAG AA limit for 12px text,
 * and these captions are the safety wording.
 */
export function ScoreNote({ children }: { children: ReactNode }) {
  return <p className="text-xs opacity-75">{children}</p>;
}

/**
 * A model score (0-1) for display: two decimals, truncated rather than rounded.
 *
 * The LOW/MEDIUM/HIGH bands compare the unrounded score with 0.40 and 0.70, so
 * rounding would show 0.6951 as "0.70" beside a MEDIUM badge. Truncating keeps a
 * displayed 0.70 meaning "at or above 0.70". The small epsilon absorbs binary
 * floating-point error (0.29 * 100 is 28.999999999999996). Display only: the
 * stored score and the band calculation are not affected.
 */
export function formatModelScore(score: number): string {
  if (!Number.isFinite(score)) {
    return '-';
  }
  return (Math.trunc(score * 100 + 1e-9) / 100).toFixed(2);
}
