"""Build the model-ready dataset from the raw download.

One command turns ml/data/raw/diabetic_data.csv into the processed table used by
Milestone 2, and writes the evidence a reviewer needs:

    cd ml && python -m src.data.build_dataset

Outputs
    ml/data/processed/admissions_features.csv   model-ready table (never committed)
    docs/06-milestones/evidence/milestone-1-run.txt   run log, safe to commit
    docs/02-database/data-dictionary.md         column reference for the backend

No dataset file is ever written into a tracked directory.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

# Paths are anchored to this file, so the script runs from any directory.
ML_ROOT = Path(__file__).resolve().parents[2]
REPO_ROOT = ML_ROOT.parent
if str(ML_ROOT) not in sys.path:
    sys.path.insert(0, str(ML_ROOT))

from src.utils.config import load_config

from src.data.load_data import (
    binarise_target,
    load_id_mappings,
    load_raw,
)
from src.data.preprocess import basic_clean, decode_id_columns
from src.features.build_features import build_features

EVIDENCE_PATH = REPO_ROOT / "docs" / "06-milestones" / "evidence" / "milestone-1-run.txt"
DICTIONARY_PATH = REPO_ROOT / "docs" / "02-database" / "data-dictionary.md"

POSTGRES_TYPES = {
    "int64": "INTEGER",
    "Int64": "INTEGER",
    "float64": "NUMERIC",
    "bool": "BOOLEAN",
    "object": "VARCHAR",
    "category": "VARCHAR",
}


class RunLog:
    """Collect pipeline output for both the console and the evidence file."""

    def __init__(self) -> None:
        self.lines: list[str] = []

    def write(self, message: str = "") -> None:
        """Print a line and retain it for the evidence file."""
        print(message)
        self.lines.append(message)

    def save(self, path: Path) -> None:
        """Write the collected lines to disk, creating parent directories."""
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(self.lines) + "\n", encoding="utf-8")


def write_data_dictionary(frame: pd.DataFrame, path: Path) -> None:
    """Write a Markdown column reference for the backend and database work."""
    path.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Data dictionary - processed admissions table\n\n"
        "Generated by `ml/src/data/build_dataset.py`. Do not edit by hand.\n\n"
        "This is the contract between the ML pipeline and the PostgreSQL schema.\n\n"
        "| Column | Pandas type | PostgreSQL type | Distinct values |\n"
        "|---|---|---|---|\n"
    )
    rows = []
    for column in frame.columns:
        dtype = str(frame[column].dtype)
        postgres = POSTGRES_TYPES.get(dtype, "VARCHAR")
        rows.append(f"| `{column}` | {dtype} | {postgres} | {frame[column].nunique():,} |")
    path.write_text(header + "\n".join(rows) + "\n", encoding="utf-8")


def run(config_path: str | None = None) -> int:
    """Execute the full Milestone 1 data pipeline."""
    log = RunLog()
    config = load_config(config_path)
    dataset = config.get("dataset", {})

    raw_path = REPO_ROOT / dataset.get("raw_path", "ml/data/raw/diabetic_data.csv")
    mapping_path = raw_path.parent / "IDS_mapping.csv"
    processed_path = REPO_ROOT / dataset.get(
        "processed_path", "ml/data/processed/admissions_features.csv"
    )

    log.write("=" * 72)
    log.write("HEALTHFORECAST AI - MILESTONE 1 DATA PIPELINE")
    log.write("=" * 72)

    frame = load_raw(raw_path)
    start_rows = len(frame)
    log.write("")
    log.write("[1] LOADED RAW DATASET")
    log.write(f"    Rows: {start_rows:,}   Columns: {frame.shape[1]}")
    log.write(f"    Unique patients: {frame['patient_nbr'].nunique():,}")

    missing = (frame.isna().mean() * 100).round(2)
    missing = missing[missing > 0].sort_values(ascending=False)
    log.write("")
    log.write("[2] MISSING VALUES")
    for column, percent in missing.items():
        log.write(f"    {column:<26} {percent:>6.2f}%")

    mappings = load_id_mappings(mapping_path)
    frame = decode_id_columns(frame, mappings)
    log.write("")
    log.write("[3] DECODED IDENTIFIER COLUMNS")
    for name in ("admission_type", "discharge_disposition", "admission_source"):
        if name in frame.columns:
            log.write(f"    {name:<26} {frame[name].nunique()} categories")

    frame = basic_clean(frame, config)
    log.write("")
    log.write("[4] CLEANED")
    log.write(f"    Rows after cleaning: {len(frame):,}  (removed {start_rows - len(frame):,})")
    log.write("    Death and hospice discharges removed - they cannot be readmitted")
    log.write("    One encounter kept per patient - prevents train/test patient leakage")

    frame = build_features(frame)
    log.write("")
    log.write("[5] FEATURES BUILT")
    for column in ("total_prior_visits", "num_med_changes", "num_meds_prescribed"):
        if column in frame.columns:
            log.write(f"    {column:<26} mean {frame[column].mean():.2f}")

    target_column = dataset.get("target_column", "readmitted")
    positive_label = dataset.get("positive_label", "<30")
    frame["readmitted_30d"] = binarise_target(frame[target_column], positive_label)
    positives = int(frame["readmitted_30d"].sum())
    log.write("")
    log.write("[6] TARGET VARIABLE")
    log.write(f"    readmitted_30d = 1 when readmitted within 30 days (label '{positive_label}')")
    log.write(f"    Positive: {positives:,} ({positives / len(frame) * 100:.2f}%)")
    log.write(f"    Negative: {len(frame) - positives:,}")
    log.write("    Class imbalance - use class_weight or SMOTE in Milestone 2")

    remaining_missing = int(frame.isna().sum().sum())
    duplicate_patients = int(frame["patient_nbr"].duplicated().sum())
    log.write("")
    log.write("[7] QUALITY CHECKS")
    log.write(f"    Missing values remaining: {remaining_missing}")
    log.write(f"    Duplicate patients: {duplicate_patients}")

    processed_path.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(processed_path, index=False)
    log.write("")
    log.write("[8] WRITTEN")
    log.write(f"    Processed table: {processed_path.relative_to(REPO_ROOT)}")
    log.write(f"    Final shape: {len(frame):,} rows x {frame.shape[1]} columns")
    log.write("    This file is gitignored and is regenerated by this script.")

    write_data_dictionary(frame, DICTIONARY_PATH)
    log.write(f"    Data dictionary: {DICTIONARY_PATH.relative_to(REPO_ROOT)}")

    log.save(EVIDENCE_PATH)
    print(f"\nEvidence written to {EVIDENCE_PATH.relative_to(REPO_ROOT)}")
    return 0


def main() -> int:
    """Parse arguments and run the pipeline."""
    parser = argparse.ArgumentParser(description="Build the Milestone 1 dataset.")
    parser.add_argument("--config", default=None, help="Path to config.yaml")
    arguments = parser.parse_args()
    return run(arguments.config)


if __name__ == "__main__":
    raise SystemExit(main())
